/**
 * Schema exporters. All are generated from the same ERD as the PostgreSQL
 * DDL (erdToSql), so every format matches the diagram.
 */
import type { Column, ERD, Table } from "@/types/erd";

const isSerial = (c: Column) => /SERIAL/i.test(c.dataType);
const singlePk = (t: Table) => {
  const pk = t.columns.filter((c) => c.isPrimaryKey);
  return pk.length === 1 ? pk[0] : null;
};
const onDeleteSql = (value: string | null | undefined) => (value || "RESTRICT").replace("_", " ");
const uniqueSets = (t: Table) => t.constraints.filter((c) => c.type === "UNIQUE").map((c) => c.columns);
const checks = (t: Table) => t.constraints.filter((c) => c.type === "CHECK" && c.expression).map((c) => c.expression as string);

/** Postgres-only default expressions translated for other databases. */
function portableDefault(value: string | null, target: "mysql" | "sqlite"): string | null {
  if (!value) return null;
  const upper = value.trim().toUpperCase();
  if (upper === "NOW()" || upper === "CURRENT_TIMESTAMP" || upper === "CURRENT_TIMESTAMP()") return "CURRENT_TIMESTAMP";
  if (upper === "CURRENT_DATE") return target === "mysql" ? "(CURRENT_DATE)" : "CURRENT_DATE";
  if (upper === "TRUE") return target === "mysql" ? "TRUE" : "1";
  if (upper === "FALSE") return target === "mysql" ? "FALSE" : "0";
  if (upper.startsWith("GEN_RANDOM_UUID")) return target === "mysql" ? "(UUID())" : null;
  if (/::/.test(value)) return value.replace(/::[a-z ]+(\(\d+(,\d+)?\))?/gi, "");
  return value;
}

// ---------------------------------------------------------------------------
// MySQL 8
// ---------------------------------------------------------------------------

function mysqlType(column: Column, needsIndexable: boolean): string {
  const t = column.dataType.trim().toUpperCase();
  if (t === "SERIAL") return "INT";
  if (t === "BIGSERIAL") return "BIGINT";
  if (t === "SMALLSERIAL") return "SMALLINT";
  if (t === "INTEGER" || t === "INT4") return "INT";
  if (/^TIMESTAMPTZ|TIMESTAMP WITH TIME ZONE/.test(t)) return "DATETIME";
  if (/^TIMESTAMP/.test(t)) return "DATETIME";
  if (t === "UUID") return "CHAR(36)";
  if (/^JSONB?$/.test(t)) return "JSON";
  if (/^NUMERIC/.test(t)) return t.replace("NUMERIC", "DECIMAL");
  if (t === "REAL") return "FLOAT";
  if (t === "DOUBLE PRECISION") return "DOUBLE";
  if (t === "BYTEA") return "BLOB";
  if (t === "TEXT" && needsIndexable) return "VARCHAR(255)";
  return t;
}

export function erdToMysql(erd: ERD): string {
  const q = (name: string) => `\`${name}\``;
  const blocks = erd.tables.map((table) => {
    const indexed = new Set([
      ...uniqueSets(table).flat(),
      ...table.indexes.flatMap((i) => i.columns),
      ...table.columns.filter((c) => c.isPrimaryKey || c.isForeignKey).map((c) => c.name),
    ]);
    const lines = table.columns.map((column) => {
      let line = `  ${q(column.name)} ${mysqlType(column, indexed.has(column.name))}`;
      if (!column.nullable) line += " NOT NULL";
      if (isSerial(column)) line += " AUTO_INCREMENT";
      const def = isSerial(column) ? null : portableDefault(column.defaultValue, "mysql");
      // MySQL only allows expression defaults (in parentheses) on JSON/TEXT/BLOB.
      const needsParens = /^(JSON|TEXT|BLOB)/.test(mysqlType(column, false)) && def && !def.startsWith("(");
      if (def) line += ` DEFAULT ${needsParens ? `(${def})` : def}`;
      return line;
    });
    const pk = table.columns.filter((c) => c.isPrimaryKey).map((c) => q(c.name));
    if (pk.length) lines.push(`  PRIMARY KEY (${pk.join(", ")})`);
    for (const set of uniqueSets(table)) lines.push(`  UNIQUE KEY ${q(`uq_${table.name}_${set.join("_")}`.slice(0, 64))} (${set.map(q).join(", ")})`);
    for (const expression of checks(table)) lines.push(`  CHECK (${expression.replace(/::[a-z ]+(\(\d+(,\d+)?\))?/gi, "")})`);
    for (const index of table.indexes) {
      lines.push(`  ${index.unique ? "UNIQUE " : ""}KEY ${q(index.name.slice(0, 64))} (${index.columns.map(q).join(", ")})`);
    }
    return `CREATE TABLE ${q(table.name)} (\n${lines.join(",\n")}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;`;
  });

  const fks = erd.relationships.map(
    (r) =>
      `ALTER TABLE ${q(r.fromTable)} ADD CONSTRAINT ${q(`fk_${r.fromTable}_${r.fromColumn}`.slice(0, 64))} FOREIGN KEY (${q(r.fromColumn)}) REFERENCES ${q(r.toTable)} (${q(r.toColumn)}) ON DELETE ${onDeleteSql(r.onDelete)};`
  );

  return ["-- MySQL 8 schema generated by Episteme", ...blocks, ...fks].join("\n\n") + "\n";
}

// ---------------------------------------------------------------------------
// SQLite
// ---------------------------------------------------------------------------

function sqliteType(column: Column): string {
  const t = column.dataType.toUpperCase();
  if (/INT|SERIAL/.test(t)) return "INTEGER";
  if (/NUMERIC|DECIMAL/.test(t)) return "NUMERIC";
  if (/REAL|FLOAT|DOUBLE/.test(t)) return "REAL";
  if (/BOOL/.test(t)) return "INTEGER";
  if (/BYTEA|BLOB/.test(t)) return "BLOB";
  return "TEXT";
}

export function erdToSqlite(erd: ERD): string {
  const blocks = erd.tables.map((table) => {
    const pk = singlePk(table);
    const autoPk = pk && isSerial(pk) ? pk : null;
    const lines = table.columns.map((column) => {
      if (column === autoPk) return `  ${column.name} INTEGER PRIMARY KEY AUTOINCREMENT`;
      let line = `  ${column.name} ${sqliteType(column)}`;
      if (!column.nullable) line += " NOT NULL";
      const def = portableDefault(column.defaultValue, "sqlite");
      if (def) line += ` DEFAULT ${/^[A-Z_]+$/.test(def) || /^-?[\d.]+$/.test(def) || def.startsWith("'") ? def : `(${def})`}`;
      const rel = erd.relationships.find((r) => r.fromTable === table.name && r.fromColumn === column.name);
      if (rel) line += ` REFERENCES ${rel.toTable} (${rel.toColumn}) ON DELETE ${onDeleteSql(rel.onDelete)}`;
      return line;
    });
    const pkCols = table.columns.filter((c) => c.isPrimaryKey && c !== autoPk).map((c) => c.name);
    if (!autoPk && pkCols.length) lines.push(`  PRIMARY KEY (${pkCols.join(", ")})`);
    for (const set of uniqueSets(table)) lines.push(`  UNIQUE (${set.join(", ")})`);
    for (const expression of checks(table)) lines.push(`  CHECK (${expression.replace(/::[a-z ]+/gi, "")})`);
    return `CREATE TABLE ${table.name} (\n${lines.join(",\n")}\n);`;
  });
  const indexes = erd.tables.flatMap((table) =>
    table.indexes.map((i) => `CREATE ${i.unique ? "UNIQUE " : ""}INDEX ${i.name} ON ${table.name} (${i.columns.join(", ")});`)
  );
  return ["-- SQLite schema generated by Episteme", "PRAGMA foreign_keys = ON;", ...blocks, ...indexes].join("\n\n") + "\n";
}

// ---------------------------------------------------------------------------
// Prisma
// ---------------------------------------------------------------------------

const pascal = (name: string) =>
  name
    .split("_")
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
const camel = (name: string) => {
  const p = pascal(name);
  return p ? p[0].toLowerCase() + p.slice(1) : name;
};
const singularize = (name: string) =>
  name.endsWith("ies") ? `${name.slice(0, -3)}y` : /(ss|x|ch|sh)es$/.test(name) ? name.slice(0, -2) : name.endsWith("s") && !name.endsWith("ss") ? name.slice(0, -1) : name;
const modelName = (table: string) => pascal(singularize(table));

function prismaScalar(column: Column): { type: string; native: string | null } {
  const t = column.dataType.toUpperCase();
  if (/BIGSERIAL|BIGINT/.test(t)) return { type: "BigInt", native: null };
  if (/SMALLINT|SMALLSERIAL/.test(t)) return { type: "Int", native: "@db.SmallInt" };
  if (/INT|SERIAL/.test(t)) return { type: "Int", native: null };
  if (/BOOL/.test(t)) return { type: "Boolean", native: null };
  if (/TIMESTAMPTZ|WITH TIME ZONE/.test(t)) return { type: "DateTime", native: "@db.Timestamptz" };
  if (/TIMESTAMP/.test(t)) return { type: "DateTime", native: "@db.Timestamp" };
  if (/^DATE/.test(t)) return { type: "DateTime", native: "@db.Date" };
  if (/NUMERIC|DECIMAL/.test(t)) {
    const m = t.match(/\((\d+)\s*,\s*(\d+)\)/);
    return { type: "Decimal", native: m ? `@db.Decimal(${m[1]}, ${m[2]})` : null };
  }
  if (/REAL|FLOAT|DOUBLE/.test(t)) return { type: "Float", native: null };
  if (/JSON/.test(t)) return { type: "Json", native: null };
  if (/UUID/.test(t)) return { type: "String", native: "@db.Uuid" };
  if (/BYTEA/.test(t)) return { type: "Bytes", native: null };
  const varchar = t.match(/VARCHAR\((\d+)\)|CHARACTER VARYING\((\d+)\)/);
  if (varchar) return { type: "String", native: `@db.VarChar(${varchar[1] ?? varchar[2]})` };
  return { type: "String", native: null };
}

function prismaDefault(column: Column): string | null {
  if (isSerial(column)) return "@default(autoincrement())";
  const value = column.defaultValue?.trim();
  if (!value) return null;
  const upper = value.toUpperCase();
  if (upper === "NOW()" || upper.startsWith("CURRENT_TIMESTAMP")) return "@default(now())";
  if (upper.startsWith("GEN_RANDOM_UUID")) return "@default(dbgenerated(\"gen_random_uuid()\"))";
  if (upper === "TRUE" || upper === "FALSE") return `@default(${upper.toLowerCase()})`;
  if (/^-?\d+(\.\d+)?$/.test(value)) return `@default(${value})`;
  const str = value.match(/^'(.*)'(::.*)?$/);
  if (str) return `@default("${str[1].replace(/"/g, '\\"')}")`;
  return `@default(dbgenerated("${value.replace(/"/g, '\\"')}"))`;
}

const PRISMA_ON_DELETE: Record<string, string> = { CASCADE: "Cascade", SET_NULL: "SetNull", RESTRICT: "Restrict", NO_ACTION: "NoAction" };

export function erdToPrisma(erd: ERD): string {
  const out: string[] = [
    "// Prisma schema generated by Episteme",
    "",
    "generator client {",
    '  provider = "prisma-client-js"',
    "}",
    "",
    "datasource db {",
    '  provider = "postgresql"',
    '  url      = env("DATABASE_URL")',
    "}",
  ];

  for (const table of erd.tables) {
    const lines: string[] = [];
    const pkCols = table.columns.filter((c) => c.isPrimaryKey);
    const used = new Set(table.columns.map((c) => camel(c.name)));

    for (const column of table.columns) {
      const { type, native } = prismaScalar(column);
      const attrs = [
        pkCols.length === 1 && column.isPrimaryKey ? "@id" : null,
        prismaDefault(column),
        uniqueSets(table).some((s) => s.length === 1 && s[0] === column.name) || table.indexes.some((i) => i.unique && i.columns.length === 1 && i.columns[0] === column.name)
          ? "@unique"
          : null,
        native,
        camel(column.name) !== column.name ? `@map("${column.name}")` : null,
      ].filter(Boolean);
      lines.push(`  ${camel(column.name)} ${type}${column.nullable && !column.isPrimaryKey ? "?" : ""}${attrs.length ? ` ${attrs.join(" ")}` : ""}`);
    }

    // Relations owned by this table (it holds the FK).
    const outgoing = erd.relationships.filter((r) => r.fromTable === table.name);
    for (const rel of outgoing) {
      // Prisma needs a relation name when two tables are linked more than
      // once, or when a table references itself.
      const many =
        rel.fromTable === rel.toTable ||
        erd.relationships.filter((r) => r.fromTable === rel.fromTable && r.toTable === rel.toTable).length > 1;
      const relationName = many ? `"${rel.fromTable}_${rel.fromColumn}"` : null;
      let field = camel(rel.fromColumn.replace(/_id$/, "")) || camel(singularize(rel.toTable));
      if (used.has(field)) field = `${field}Rel`;
      used.add(field);
      const column = table.columns.find((c) => c.name === rel.fromColumn);
      const args = [
        relationName,
        `fields: [${camel(rel.fromColumn)}]`,
        `references: [${camel(rel.toColumn)}]`,
        `onDelete: ${PRISMA_ON_DELETE[rel.onDelete] ?? "Restrict"}`,
      ].filter(Boolean);
      lines.push(`  ${field} ${modelName(rel.toTable)}${column?.nullable ? "?" : ""} @relation(${args.join(", ")})`);
    }

    // Back-relations from tables that reference this one.
    const incoming = erd.relationships.filter((r) => r.toTable === table.name);
    for (const rel of incoming) {
      const many =
        rel.fromTable === rel.toTable ||
        erd.relationships.filter((r) => r.fromTable === rel.fromTable && r.toTable === rel.toTable).length > 1;
      const childTable = erd.tables.find((t) => t.name === rel.fromTable);
      const oneToOne = rel.cardinality === "1:1" || (childTable ? uniqueSets(childTable).some((s) => s.length === 1 && s[0] === rel.fromColumn) : false);
      let field = camel(many ? `${rel.fromTable}_by_${rel.fromColumn.replace(/_id$/, "")}` : oneToOne ? singularize(rel.fromTable) : rel.fromTable);
      if (used.has(field)) field = `${field}List`;
      used.add(field);
      lines.push(`  ${field} ${modelName(rel.fromTable)}${oneToOne ? "?" : "[]"}${many ? ` @relation("${rel.fromTable}_${rel.fromColumn}")` : ""}`);
    }

    if (pkCols.length > 1) lines.push(`\n  @@id([${pkCols.map((c) => camel(c.name)).join(", ")}])`);
    for (const set of uniqueSets(table).filter((s) => s.length > 1)) lines.push(`  @@unique([${set.map(camel).join(", ")}])`);
    for (const index of table.indexes.filter((i) => !(i.unique && i.columns.length === 1))) {
      lines.push(`  @@${index.unique ? "unique" : "index"}([${index.columns.map(camel).join(", ")}], map: "${index.name}")`);
    }
    if (modelName(table.name) !== table.name) lines.push(`  @@map("${table.name}")`);

    out.push("", `model ${modelName(table.name)} {`, ...lines, "}");
  }

  if (erd.tables.some((t) => checks(t).length)) {
    out.push("", "// Note: Prisma doesn't model CHECK constraints; keep them in a SQL migration.");
  }
  return out.join("\n") + "\n";
}

// ---------------------------------------------------------------------------
// Drizzle ORM (pg-core)
// ---------------------------------------------------------------------------

function drizzleColumn(column: Column): { fn: string; call: string } {
  const t = column.dataType.toUpperCase();
  const n = `"${column.name}"`;
  if (t === "SERIAL") return { fn: "serial", call: `serial(${n})` };
  if (t === "BIGSERIAL") return { fn: "bigserial", call: `bigserial(${n}, { mode: "number" })` };
  if (/BIGINT/.test(t)) return { fn: "bigint", call: `bigint(${n}, { mode: "number" })` };
  if (/SMALLINT/.test(t)) return { fn: "smallint", call: `smallint(${n})` };
  if (/INT/.test(t)) return { fn: "integer", call: `integer(${n})` };
  if (/BOOL/.test(t)) return { fn: "boolean", call: `boolean(${n})` };
  if (/TIMESTAMPTZ|WITH TIME ZONE/.test(t)) return { fn: "timestamp", call: `timestamp(${n}, { withTimezone: true })` };
  if (/TIMESTAMP/.test(t)) return { fn: "timestamp", call: `timestamp(${n})` };
  if (/^DATE/.test(t)) return { fn: "date", call: `date(${n})` };
  if (/NUMERIC|DECIMAL/.test(t)) {
    const m = t.match(/\((\d+)\s*,\s*(\d+)\)/);
    return { fn: "numeric", call: m ? `numeric(${n}, { precision: ${m[1]}, scale: ${m[2]} })` : `numeric(${n})` };
  }
  if (/REAL/.test(t)) return { fn: "real", call: `real(${n})` };
  if (/DOUBLE|FLOAT/.test(t)) return { fn: "doublePrecision", call: `doublePrecision(${n})` };
  if (/JSONB/.test(t)) return { fn: "jsonb", call: `jsonb(${n})` };
  if (/JSON/.test(t)) return { fn: "json", call: `json(${n})` };
  if (/UUID/.test(t)) return { fn: "uuid", call: `uuid(${n})` };
  const varchar = t.match(/VARCHAR\((\d+)\)|CHARACTER VARYING\((\d+)\)/);
  if (varchar) return { fn: "varchar", call: `varchar(${n}, { length: ${varchar[1] ?? varchar[2]} })` };
  const char = t.match(/^CHAR\((\d+)\)/);
  if (char) return { fn: "char", call: `char(${n}, { length: ${char[1]} })` };
  return { fn: "text", call: `text(${n})` };
}

export function erdToDrizzle(erd: ERD): string {
  const imports = new Set<string>(["pgTable"]);
  const body: string[] = [];
  const varName = (table: string) => camel(table);

  for (const table of erd.tables) {
    const pkCols = table.columns.filter((c) => c.isPrimaryKey);
    const cols: string[] = [];
    for (const column of table.columns) {
      const { fn, call } = drizzleColumn(column);
      imports.add(fn);
      let expr = call;
      if (pkCols.length === 1 && column.isPrimaryKey) expr += ".primaryKey()";
      if (!column.nullable && !column.isPrimaryKey) expr += ".notNull()";
      const def = column.defaultValue?.trim();
      if (def && !isSerial(column)) {
        const upper = def.toUpperCase();
        if (upper === "NOW()" || upper.startsWith("CURRENT_TIMESTAMP")) expr += ".defaultNow()";
        else if (upper.startsWith("GEN_RANDOM_UUID")) expr += ".defaultRandom()";
        else if (upper === "TRUE" || upper === "FALSE") expr += `.default(${upper.toLowerCase()})`;
        else {
          imports.add("sql");
          expr += `.default(sql\`${def.replace(/`/g, "\\`")}\`)`;
        }
      }
      if (uniqueSets(table).some((s) => s.length === 1 && s[0] === column.name)) expr += ".unique()";
      const rel = erd.relationships.find((r) => r.fromTable === table.name && r.fromColumn === column.name);
      if (rel) {
        const onDelete = { CASCADE: "cascade", SET_NULL: "set null", RESTRICT: "restrict", NO_ACTION: "no action" }[rel.onDelete] ?? "restrict";
        const target = rel.toTable === table.name ? `(): AnyPgColumn => ${varName(rel.toTable)}.${camel(rel.toColumn)}` : `() => ${varName(rel.toTable)}.${camel(rel.toColumn)}`;
        if (rel.toTable === table.name) imports.add("type AnyPgColumn");
        expr += `.references(${target}, { onDelete: "${onDelete}" })`;
      }
      cols.push(`  ${camel(column.name)}: ${expr},`);
    }

    const extras: string[] = [];
    if (pkCols.length > 1) {
      imports.add("primaryKey");
      extras.push(`primaryKey({ columns: [${pkCols.map((c) => `t.${camel(c.name)}`).join(", ")}] })`);
    }
    for (const set of uniqueSets(table).filter((s) => s.length > 1)) {
      imports.add("unique");
      extras.push(`unique("uq_${table.name}_${set.join("_")}").on(${set.map((c) => `t.${camel(c)}`).join(", ")})`);
    }
    for (const index of table.indexes) {
      imports.add(index.unique ? "uniqueIndex" : "index");
      extras.push(`${index.unique ? "uniqueIndex" : "index"}("${index.name}").on(${index.columns.map((c) => `t.${camel(c)}`).join(", ")})`);
    }
    checks(table).forEach((expression, i) => {
      imports.add("check");
      imports.add("sql");
      extras.push(`check("ck_${table.name}_${i + 1}", sql\`${expression.replace(/`/g, "\\`")}\`)`);
    });

    body.push(
      `export const ${varName(table.name)} = pgTable("${table.name}", {\n${cols.join("\n")}\n}${extras.length ? `, (t) => [\n  ${extras.join(",\n  ")},\n]` : ""});`
    );
  }

  const coreImports = [...imports].filter((i) => i !== "sql").sort();
  const header = [
    "// Drizzle ORM schema generated by Episteme",
    `import { ${coreImports.join(", ")} } from "drizzle-orm/pg-core";`,
    imports.has("sql") ? `import { sql } from "drizzle-orm";` : null,
  ].filter(Boolean);
  return [...header, "", ...body].join("\n\n").replace(/\n\n\n+/g, "\n\n") + "\n";
}
