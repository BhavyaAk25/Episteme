import type { ERD } from "@/types/erd";
import type { VerifyRun } from "@/lib/verify/runner";
import type { Issue } from "@/lib/verify/linter";
import { escapeHtml } from "@/lib/utils/escapeHtml";

/** Standalone HTML report: design issues and Postgres test results. */
export function buildReportHtml(args: { name: string; prompt: string; erd: ERD; issues: Issue[]; run: VerifyRun | null }): string {
  const { name, prompt, erd, issues, run } = args;
  const passed = run?.tests.filter((t) => t.status === "pass").length ?? 0;
  const failed = run?.tests.filter((t) => t.status === "fail").length ?? 0;
  const skipped = run?.tests.filter((t) => t.status === "skip").length ?? 0;

  const issueRows = issues.length
    ? issues
        .map((i) => `<tr><td class="sev ${i.severity}">${escapeHtml(i.severity)}</td><td>${escapeHtml(i.title)}</td><td>${escapeHtml(i.detail)}</td></tr>`)
        .join("")
    : `<tr><td colspan="3">No issues found.</td></tr>`;

  const testRows = run
    ? run.tests
        .map((t) => `<tr><td class="st ${t.status}">${escapeHtml(t.status)}</td><td>${escapeHtml(t.title)}</td><td>${escapeHtml(t.status === "pass" ? "" : t.detail ?? "")}</td></tr>`)
        .join("")
    : `<tr><td colspan="3">Postgres tests weren't run before export.</td></tr>`;

  const ddl = run?.ddlProblems.length
    ? `<h2>SQL errors</h2><ul>${run.ddlProblems.map((p) => `<li><b>${escapeHtml(p.table ?? "schema")}</b>: ${escapeHtml(p.error)}</li>`).join("")}</ul>`
    : "";

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(name)} — Episteme report</title>
<style>
  body{font:14px/1.5 system-ui,sans-serif;margin:0;padding:32px;color:#2b2218;background:#faf6f0;max-width:1000px}
  h1{font-size:22px;margin:0 0 4px} h2{font-size:16px;margin:28px 0 8px} .meta{color:#7b6a56;margin:2px 0}
  .stats{display:flex;gap:12px;flex-wrap:wrap;margin:16px 0}.stat{background:#fff;border:1px solid #e4d6c1;border-radius:8px;padding:8px 12px}
  table{width:100%;border-collapse:collapse;background:#fff;border:1px solid #e4d6c1}th,td{padding:6px 8px;border-bottom:1px solid #efe5d6;text-align:left;vertical-align:top}
  th{background:#f3eadc;font-size:12px;text-transform:uppercase;letter-spacing:.04em}.sev,.st{font-weight:600;text-transform:capitalize;white-space:nowrap}
  .error,.fail{color:#b14f42}.warning{color:#b8811a}.info,.skip{color:#7b8aa0}.pass{color:#237d54}
</style></head><body>
<h1>${escapeHtml(name)}</h1>
<p class="meta">Generated by Episteme on ${escapeHtml(new Date().toISOString().replace("T", " ").slice(0, 19))} UTC</p>
${prompt ? `<p class="meta">Description: ${escapeHtml(prompt)}</p>` : ""}
<div class="stats">
  <div class="stat">${erd.tables.length} tables · ${erd.relationships.length} relationships</div>
  <div class="stat">${issues.filter((i) => i.severity === "error").length} errors · ${issues.filter((i) => i.severity === "warning").length} warnings</div>
  <div class="stat">${run ? `Postgres tests: ${passed} passed, ${failed} failed, ${skipped} skipped` : "Postgres tests not run"}</div>
</div>
${ddl}
<h2>Design issues</h2><table><thead><tr><th>Severity</th><th>Issue</th><th>Details</th></tr></thead><tbody>${issueRows}</tbody></table>
<h2>Postgres tests</h2><table><thead><tr><th>Result</th><th>Test</th><th>Details</th></tr></thead><tbody>${testRows}</tbody></table>
</body></html>
`;
}
