"use client";

import { useCallback, useEffect } from "react";
import Image from "next/image";
import { useProjectStore } from "@/store/useProjectStore";
import { useSimulationStore } from "@/store/useSimulationStore";
import { useIssues } from "@/lib/verify/useIssues";
import { useUIStore } from "@/store/useUIStore";
import { useErdStore } from "@/store/useErdStore";
import { SaveIndicator } from "./SaveIndicator";
import { ProjectSwitcher } from "@/components/projects/ProjectSwitcher";
import { ThemeToggle } from "@/components/shared/ThemeToggle";
import { generateSchema } from "@/lib/actions/generateSchema";
import { MAX_PROMPT_LENGTH } from "@/lib/limits";

export function TopBar() {
  const {
    prompt,
    setPrompt,
    isGenerating,
    generationMode,
    fallbackDomain,
    generationWarning,
  } = useProjectStore();
  const erd = useErdStore((state) => ((state.erd?.tables.length ?? 0) > 0 ? state.erd : null));
  const isSimulating = useSimulationStore((state) => state.isRunning);
  const { openExportModal } = useUIStore();
  const issues = useIssues();
  const problemCount = issues.filter((issue) => issue.severity !== "info").length;

  const handleGenerate = useCallback(async () => {
    await generateSchema();
  }, []);

  const handleRunTests = useCallback(() => {
    if (!erd || isSimulating) return;
    useUIStore.getState().openDrawer();
    void useSimulationStore.getState().runTests();
  }, [erd, isSimulating]);

  const handleExport = useCallback(() => {
    if (!erd) return;
    openExportModal();
  }, [erd, openExportModal]);

  // Shortcuts that don't fight the browser: ⌘/Ctrl+Enter generates
  // (Enter in the prompt box works too).
  useEffect(() => {
    const onKeyDown = (event: KeyboardEvent) => {
      if ((event.metaKey || event.ctrlKey) && event.key === "Enter") {
        event.preventDefault();
        void handleGenerate();
      }
    };
    window.addEventListener("keydown", onKeyDown);
    return () => window.removeEventListener("keydown", onKeyDown);
  }, [handleGenerate]);

  const templateLabel = (id: string | null) =>
    id === "saas" ? "SaaS" : id === "ecommerce" ? "E-Commerce" : id === "inventory" ? "Inventory" : null;

  const status: { text: string; tone: string; title: string } | null = isGenerating
    ? { text: "Generating…", tone: "bg-foreground/[0.05] text-muted", title: "Generating schema" }
    : generationMode === "gemini"
      ? { text: "AI-generated schema", tone: "bg-success/15 text-success", title: "Generated by the AI model from your description" }
      : generationMode === "fallback"
        ? {
            text: `${templateLabel(fallbackDomain) ?? "Built-in"} template (AI unavailable)`,
            tone: "bg-warning/15 text-warning",
            title: generationWarning ?? "Showing a built-in template",
          }
        : null;


  return (
    <header className="relative z-40 bg-surface/94 backdrop-blur border-b border-border px-4 md:px-6 pt-[calc(env(safe-area-inset-top,0px)+12px)] shadow-[0_6px_18px_rgba(86,61,38,0.08)]">
      <div className="min-h-[72px] py-2 flex items-center">
        <div className="flex flex-wrap lg:flex-nowrap items-center gap-x-4 gap-y-2 w-full min-w-0">
          <div className="flex items-center gap-2.5 shrink-0">
            <div className="w-10 h-10 flex items-center justify-center">
              <Image src="/brand/episteme-mark.svg" alt="Episteme" width={40} height={40} className="logo-light w-10 h-10 object-contain" priority />
              <Image src="/brand/episteme-mark-dark.svg" alt="" aria-hidden="true" width={40} height={40} className="logo-dark w-10 h-10 object-contain" />
            </div>
            <span className="font-display text-[1.6rem] leading-none tracking-tight text-foreground hidden lg:block">
              Episteme
            </span>
          </div>
          <ProjectSwitcher />
          <SaveIndicator />

          {/* On narrow screens the description gets its own full-width row. */}
          <div className="order-last basis-full lg:order-none lg:basis-auto lg:flex-1 min-w-0">
            <input
              type="text"
              value={prompt}
              onChange={(e) => setPrompt(e.target.value, null)}
              maxLength={MAX_PROMPT_LENGTH}
              aria-label="System description"
              onKeyDown={(e) => e.key === "Enter" && handleGenerate()}
              placeholder="Describe your system... (e.g., 'inventory management for sneaker brand')"
              className="w-full min-w-0 h-11 px-4 rounded-xl bg-canvas border border-border text-foreground text-[0.95rem] placeholder:text-muted focus:outline-none focus:border-accent focus:ring-2 focus:ring-accent/20 transition-colors"
              disabled={isGenerating}
            />
          </div>

          <button
            onClick={handleGenerate}
            title="Generate (⌘/Ctrl + Enter)"
            disabled={!prompt.trim() || isGenerating}
            className="ui-primary-btn disabled:opacity-50 disabled:cursor-not-allowed transition-colors flex items-center gap-1.5 shrink-0"
          >
            {isGenerating ? (
              <>
                <span className="w-3.5 h-3.5 border-2 border-brand-ink/30 border-t-brand-ink rounded-full animate-spin" />
                Generating...
              </>
            ) : (
              "Generate"
            )}
          </button>

          <div className="flex items-center gap-2 lg:gap-3 shrink-0 ml-auto lg:ml-0">
            <button
              onClick={handleRunTests}
              data-tour="run-tests"
              title="Run the schema in real Postgres and test every rule"
              disabled={!erd || isSimulating || isGenerating}
              className="ui-ghost-btn disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              {isSimulating ? "Testing…" : "Run tests"}
            </button>
            <button
              onClick={() => useUIStore.getState().openDrawer()}
              disabled={!erd}
              title="Design issues and test results"
              className="ui-ghost-btn disabled:opacity-50 disabled:cursor-not-allowed transition-colors flex items-center gap-1.5"
            >
              Issues
              {erd && (
                <span
                  className={`min-w-5 h-5 px-1.5 rounded-full text-[11px] font-semibold inline-flex items-center justify-center ${
                    problemCount ? "bg-warning/15 text-warning" : "bg-success/15 text-success"
                  }`}
                >
                  {problemCount}
                </span>
              )}
            </button>
            <ThemeToggle />
            <button
              onClick={handleExport}
              data-tour="export"
              title="Export"
              disabled={!erd}
              className="ui-ghost-btn disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              Export
            </button>
          </div>
        </div>
      </div>

      {generationMode === "fallback" && !isGenerating && (
        <div className="h-9 flex items-center gap-3 border-t border-border/60 text-[12px]">
          <span className="inline-flex items-center px-2.5 py-0.5 font-medium rounded-full bg-warning/15 text-warning" title={generationWarning ?? undefined}>
            {status?.text ?? "Built-in template"}
          </span>
          <span className="text-muted truncate">The AI was unavailable, so this is the built-in template you picked.</span>
          <button onClick={handleGenerate} className="text-accent font-medium hover:underline shrink-0">
            Retry with AI
          </button>
        </div>
      )}
    </header>
  );
}
